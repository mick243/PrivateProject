-- ============================================================
-- 082 · 운영 알림 지우기 (ops_alerts.dismissed_at)
--
-- ─── 왜 ──────────────────────────────────────────────────
-- 관리자 화면의 종 아이콘 목록(components/OpsAlertBell.tsx)에서 알림을 하나씩, 또는 풀린 것을
-- 한꺼번에 지울 수 있게 합니다. 시험 알림은 풀림이 오지 않아 지우지 않으면 30일 동안
-- "울리는 중" 으로 남았습니다.
--
-- ─── 왜 줄을 지우지 않고 시각만 찍나 ──────────────────────
-- Grafana 는 울리는 동안 같은 알림을 몇 시간마다 다시 보내고, 풀리면 풀림을 보냅니다.
-- 줄을 진짜 지우면 그다음 반복이 "처음 보는 사건" 이 되어 목록에 다시 뜨고, 요약(Gemini)을
-- 또 만들고, 기기 푸시도 또 갑니다. 그래서 (지문, 시작 시각) 줄은 남겨 같은 사건으로 알아보고,
-- 목록과 안 읽은 수에서만 뺍니다. 지운 사건의 풀림은 상태만 맞추고 알리지 않습니다
-- (lib/ops-alerts.ts recordAlerts). 같은 규칙이 **새로** 울리면 시작 시각이 달라 다시 뜹니다.
--
-- 지운 줄도 30일이 지나면 받는 쪽이 진짜 지웁니다 (081 과 같음).
--
-- ⚠ 여러 번 실행해도 결과가 같아야 합니다.
-- ============================================================

ALTER TABLE ops_alerts ADD COLUMN IF NOT EXISTS dismissed_at TIMESTAMPTZ;

COMMENT ON COLUMN ops_alerts.dismissed_at IS
  '관리자가 목록에서 지운 시각. NULL 이면 목록에 뜬다. 같은 사건의 반복 · 풀림은 이 줄에 맞추고 다시 띄우지 않는다 (migrate-082)';
